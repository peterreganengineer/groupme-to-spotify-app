let developerToken = null;
let musicKitToken = null;

/**
 * Function to set api tokens when webpage loads
 */
document.addEventListener("DOMContentLoaded", async function () {
  console.log("The page has loaded!");
  developerToken = await fetchDeveloperToken();
  console.log(developerToken);

  musicKitToken = await authMusicKit(developerToken);
  console.log("Tokens set!");
});

/**
 * Function to call python script hosted on flask server in the backend to get developer token
 *
 * @returns developerToken - apple music developer token
 */
async function fetchDeveloperToken() {
  try {
    const response = await fetch("http://127.0.0.1:5000/developer-token");
    const data = await response.json();
    return data.developer_token;
  } catch (error) {
    console.error("Error fetching developer token:", error);
    return null;
  }
}

/**
 * Function to configure musickit instance to auth user into apple music and generate musickistToken
 * needed to authenticate before making apple music api requests.
 *
 * @param {string} devloperToken - apple music developer token generated by python script
 * @returns
 */
async function authMusicKit(devloperToken) {
  try {
    await MusicKit.configure({
      developerToken: devloperToken,
      app: {
        name: "Peter's MusicKit App",
        build: "1978.4.1",
      },
    });
    console.log("test");
    // MusicKit instance is available
    const music = MusicKit.getInstance();

    return (musicKitToken = await music.authorize());
  } catch (error) {
    console.error("Error:", error);
    alert("An error occurred. Check the console for details.");
  }
}

/**
 * main function that will create an apple music playlist
 *
 * @returns
 */
async function spotifyToApplePlaylist() {
  const spotifyPlaylistName = document.getElementById(
    "spotify_playlist_name"
  ).value;
  const applePlaylistName = document.getElementById(
    "apple_playlist_name"
  ).value;

  if (!applePlaylistName || !spotifyPlaylistName) {
    alert("Please enter both spotify and apple playlist names.");
    return;
  }
  try {
    let spotifyTracks = await fetchSpotifyTracks(spotifyPlaylistName)
    let appleTracks = await processTracks(spotifyTracks,developerToken)
    const response = await createPlaylistRequest(
      applePlaylistName,
      developerToken,
      musicKitToken
    );

    const applePlaylist = await response.json()
    const applePlaylistId = applePlaylist.data[0].id
    await addTracksToPlaylist(
      applePlaylistId,
      appleTracks,
      developerToken,
      musicKitToken
    )

    if (spotifyTracks.status === 201) {
      alert(`Playlist '${applePlaylistName}' created successfully!`);
    } else {
      const errorMessage = await response.json();
      alert(`Failed to create playlist: ${errorMessage.errors[0].detail}`);
    }
  } catch (error) {
    console.error("Error:", error);
    alert("An error occurred. Check the console for details.");
  }
}

/**
 * 
 * @param {string} track - track search term (song artist)
 * @param {string} developerToken - apple music developer token generated by python script
 * @returns single track's data
 */
async function fetchTrackData(track, developerToken) {
  const trackResponse = await searchSongRequest(
    track.name + " " + track.artists[0],
    1,
    developerToken
  );
  const trackData = await trackResponse.json();
  return trackData.results.songs.data[0];
}

/**
 * 
 * @param {*} developerToken 
 * @returns list of apple music tracks for apple music add tracks to playlist payload
 */
async function processTracks(spotifyTracks, developerToken) {
  // Fetch all track data concurrently
  const appleTrackIds = await Promise.all(
    spotifyTracks.map(track => fetchTrackData(track, developerToken))
  );

  // Create a new list with just the id and type fields
  const result = appleTrackIds.map(item => ({
    id: item.id,
    type: item.type
  }));
  return result
}

/**
 * Function to execute flask server request that returns a list of spotify tracks given a playlistName
 *
 * @returns developerToken - apple music developer token
 */
async function fetchSpotifyTracks(playlistName) {
  try {
    const encodedPlaylistName = encodeURIComponent(playlistName);
    const url =
      `http://127.0.0.1:5000/spotify-tracks?playlistName=${playlistName}`
    const response = await fetch(url);
    const data = await response.json();
    return data;
  } catch (error) {
    console.error("Error fetching developer token:", error);
    return null;
  }
}

/**
 *
 * @param {string} searchTerm - the thing to search for, song title, artist, combination of the two, etc.
 * @param {number} limit - the number of returnes search results
 * @param {string} developerToken - apple music developer token generated by python script
 */
async function searchSongRequest(searchTerm, limit = 1, developerToken) {
  const url =
    "https://api.music.apple.com/v1/catalog/us/search?term=" +
    searchTerm +
    "&limit=" +
    limit;
  const headers = {
    Authorization: `Bearer ${developerToken}`,
    "Content-Type": "application/json",
  };
  return fetch(url, {
    method: "GET",
    headers: headers,
  });
}

/**
 * Create an applemusic playlist with a given name
 *
 * @param {string} playlistName - the name of the playlist
 * @param {string} developerToken - apple music developer token generated by python script
 * @param {string} musicKitToken - music kit token returned by the function authMusicKit()
 * @returns
 */
async function createPlaylistRequest(
  playlistName,
  developerToken,
  musicKitToken
) {
  const url = "https://api.music.apple.com/v1/me/library/playlists";
  const headers = {
    Authorization: `Bearer ${developerToken}`,
    "Music-User-Token": musicKitToken,
    "Content-Type": "application/json",
  };
  const payload = {
    attributes: {
      name: playlistName,
      description: `Playlist created with the name ${playlistName}`,
    },
  };
  return fetch(url, {
    method: "POST",
    headers: headers,
    body: JSON.stringify(payload),
  });
}

/**
 * 
 * @param {string} playlistId - id of created library playlist
 * @param {dict} tracks - list of tracks (including id and type)
 * @param {string} developerToken - apple music developer token generated by python script
 * @param {string} musicKitToken - music kit token returned by the function authMusicKit()
 * @returns 
 */
async function addTracksToPlaylist(playlistId, tracks, developerToken, userToken) {
  const encodedPlaylistId = encodeURIComponent(playlistId);
  const url = `https://api.music.apple.com/v1/me/library/playlists/${encodedPlaylistId}/tracks`;
  const payload = {
    data: tracks
  };

  try {
    const response = await fetch(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${developerToken}`,
        'Music-User-Token': userToken
      },
      body: JSON.stringify(payload)
    });

    if (response.ok) {
      console.log('Tracks added successfully');
    } else {
      const errorData = await response.json();
      console.error('Error:', response.status, response.statusText, errorData);
    }
  } catch (error) {
    console.error('Network error:', error);
  }
}
